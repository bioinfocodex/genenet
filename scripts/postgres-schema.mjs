#!/usr/bin/env node
/**
 * Derive the PostgreSQL schema from the SQLite one.
 *
 * Prisma will not take the provider from an environment variable, so a
 * deployment on PostgreSQL needs a schema file saying so. Keeping a second
 * one by hand means keeping two schemas in step for ever, and they would not
 * stay in step -- the Postgres one would be edited when somebody remembered.
 *
 * So it is derived, here, and the derivation is one line: the provider. If
 * that ever stops being true, this script is where it will become obvious,
 * because it will need a second rule.
 *
 *   node scripts/postgres-schema.mjs            # write prisma/schema.postgres.prisma
 *   node scripts/postgres-schema.mjs --check    # fail if it is out of date
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'prisma', 'schema.prisma');
const target = path.join(root, 'prisma', 'schema.postgres.prisma');

const original = await readFile(source, 'utf8');

if (!/provider\s*=\s*"sqlite"/.test(original)) {
  console.error('prisma/schema.prisma no longer says provider = "sqlite". Check this script still makes sense.');
  process.exit(2);
}

const derived =
  '// Generated by scripts/postgres-schema.mjs. Do not edit.\n'
  + '//\n'
  + '// The PostgreSQL form of prisma/schema.prisma, which differs only in the\n'
  + '// provider. Edit the SQLite schema and run the script; CI checks the two\n'
  + '// are in step, so they cannot drift apart unnoticed.\n'
  + original.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = await readFile(target, 'utf8'); } catch { /* missing counts as out of date */ }
  if (current !== derived) {
    console.error(
      'prisma/schema.postgres.prisma is out of date.\n'
      + 'Run: node scripts/postgres-schema.mjs',
    );
    process.exit(1);
  }
  console.error('The PostgreSQL schema is in step with the SQLite one.');
  process.exit(0);
}

await writeFile(target, derived);
console.error(`Wrote ${path.relative(root, target)}`);
